// Emits client.gateway_ui.js, the classic-script chunk the DSH browser
// loader can fetch, from generated/gateway_ui.mjs, the ESM artifact the
// compiler prints.
//
// Why this file exists (measured, 2026-11-25): the DSH client chunk loader
// only accepts files named client.<name>.js and loads them as CLASSIC
// scripts, which cannot carry `export` statements. The generator emits an
// ES module. This emitter performs ONE mechanical lowering between the two:
// strip the `export` keyword prefixes, wrap the body in a factory, and
// return every declaration the generator itself lists in __DECL_ORDER__
// (plus the three generator bookkeeping exports). It invents no value, no
// threshold, no label, no token; a transformed value would be a second home
// for the law and is refused below.
//
// This is the same documented platform-bridge exception as the logic
// artifact's composition section: the law lives in the spec, the build
// composes the runtime shape the platform requires, and the emitter fails
// loudly rather than shipping a half-emitted module.
//
// Run: node scripts/emit_client_gateway_ui.mjs  (build.sh calls this)
// Library use: import { emitClientChunk } from this file (the contract test
// does, so the emitted wrapper is pinned, not just produced).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const CHUNK_ID = '@local/t27-gateway/client.gateway_ui.js';
const BOOKKEEPING = ['__STRUCT_ORDER__', '__DECL_ORDER__', '__NOT_EMITTED__'];

export function emitClientChunk(source) {
  // A module the generator refused to finish must never reach the browser
  // with missing names: the panel would crash on an undefined law.
  const notEmitted = source.match(/export const __NOT_EMITTED__ = Object\.freeze\(\[([^\]]*)\]\);/);
  if (notEmitted === null) {
    throw new Error('emit: generated/gateway_ui.mjs has no parsable __NOT_EMITTED__ declaration');
  }
  if (notEmitted[1].trim() !== '') {
    throw new Error('emit: generator refused declarations (__NOT_EMITTED__ is non-empty): ' + notEmitted[1]);
  }

  const declOrder = source.match(/export const __DECL_ORDER__ = (\[[^\]]*\]);/);
  if (declOrder === null) {
    throw new Error('emit: generated/gateway_ui.mjs has no __DECL_ORDER__ declaration');
  }
  const names = JSON.parse(declOrder[1]);
  if (names.length === 0) {
    throw new Error('emit: __DECL_ORDER__ is empty; refusing to emit an empty chunk');
  }

  // Strip export prefixes. Anything else (export {, export default, export
  // const with a destructure) is a generator shape this emitter does not
  // know, and must fail rather than produce a broken classic script.
  const lines = source.split('\n').map((line) => {
    if (/^export const (\w+) =/.test(line) || /^export function (\w+)/.test(line)) {
      return line.replace(/^export /, '');
    }
    if (/^export /.test(line)) {
      throw new Error('emit: unhandled export form in generated module: ' + line);
    }
    return line;
  });

  const body = lines.join('\n');
  for (const name of names) {
    const defined =
      body.includes('const ' + name + ' ') || body.includes('function ' + name + '(');
    if (!defined) {
      throw new Error('emit: __DECL_ORDER__ lists "' + name + '" but the body never defines it');
    }
  }

  const returned = names.concat(BOOKKEEPING).join(', ');
  return [
    '// Generated by scripts/emit_client_gateway_ui.mjs from generated/gateway_ui.mjs.',
    '// Do not edit: every value here comes from spec/gateway_ui.t27. Rebuild instead.',
    'window.__ModuleLoader__.load({',
    "  id: '" + CHUNK_ID + "',",
    '  factory: function (require) {',
    body,
    '  return { ' + returned + ' };',
    '  },',
    '});',
    '',
  ].join('\n');
}

const isMain = process.argv[1] !== undefined && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const source = readFileSync(join(root, 'generated', 'gateway_ui.mjs'), 'utf8');
  const chunk = emitClientChunk(source);
  writeFileSync(join(root, 'client.gateway_ui.js'), chunk);
  process.stdout.write('emit: wrote client.gateway_ui.js (' + Buffer.byteLength(chunk) + ' bytes)\n');
}
